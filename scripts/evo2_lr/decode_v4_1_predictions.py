#!/usr/bin/env python3
"""Decode v4.1 predictions for genomes without ground truth.

Input directories must contain `{genome}_predictions.csv` files generated by
`scripts/evo2_lr/apply_lr_to_dir.py` for:
  - primary scale: w=8192/s=2048
  - short-rescue scale: w=4096/s=1024

Output:
  - `{genome}_regions.csv` per genome
  - `all_regions.csv` across genomes
  - `manifest.json`
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts"))
from postprocess_v2 import WindowScore, decode_regions_hysteresis  # noqa: E402


PRIMARY_OP = {
    "start_threshold": 0.95,
    "extend_threshold": 0.80,
    "min_support_windows": 3,
    "max_gap": 0,
}
SHORT_OP = {
    "start_threshold": 0.95,
    "extend_threshold": 0.80,
    "min_support_windows": 5,
    "max_gap": 0,
}
SHORT_LENGTH_CAP = 10_000
IOU_DEDUP = 0.3


def decode_csv(csv_path: Path, op: dict, source: str) -> list[tuple]:
    df = pd.read_csv(csv_path)
    wins = [
        WindowScore(str(r["contig"]), int(r["start"]), int(r["end"]), float(r["bgc_score"]))
        for _, r in df.iterrows()
    ]
    regs = decode_regions_hysteresis(
        wins,
        start_threshold=op["start_threshold"],
        extend_threshold=op["extend_threshold"],
        min_support_windows=op["min_support_windows"],
        max_gap=op["max_gap"],
    )
    out = []
    for r in regs:
        contig, start, end = r[0], int(r[1]), int(r[2])
        mx = 0.0
        for w in wins:
            if w.contig == contig and w.end > start and w.start < end:
                mx = max(mx, w.score)
        out.append((contig, start, end, mx, source))
    return out


def iou(a: tuple, b: tuple) -> float:
    if a[0] != b[0]:
        return 0.0
    overlap = max(0, min(a[2], b[2]) - max(a[1], b[1]))
    union = max(a[2], b[2]) - min(a[1], b[1])
    return overlap / max(1, union)


def union_dedup(primary: list[tuple], short: list[tuple], iou_thresh: float) -> list[tuple]:
    candidates = sorted(primary + short, key=lambda r: r[3], reverse=True)
    kept: list[tuple] = []
    for r in candidates:
        if not any(iou(r, k) >= iou_thresh for k in kept):
            kept.append(r)
    return sorted(kept, key=lambda r: (r[0], r[1], r[2]))


def main() -> None:
    p = argparse.ArgumentParser(description="Decode v4.1 multi-scale predictions")
    p.add_argument("--primary-preds", type=Path, required=True)
    p.add_argument("--short-preds", type=Path, default=None,
                   help="optional w=4096 prediction dir; omit for primary-only decode")
    p.add_argument("--out-dir", type=Path, required=True)
    p.add_argument("--short-length-cap", type=int, default=SHORT_LENGTH_CAP)
    p.add_argument("--iou-dedup", type=float, default=IOU_DEDUP)
    args = p.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    primary_files = {p.name[:-len("_predictions.csv")]: p
                     for p in args.primary_preds.glob("*_predictions.csv")}
    short_files = {}
    if args.short_preds is not None:
        short_files = {p.name[:-len("_predictions.csv")]: p
                       for p in args.short_preds.glob("*_predictions.csv")}
    genomes = sorted(set(primary_files) | set(short_files))

    all_rows = []
    manifest = {
        "primary_op": PRIMARY_OP,
        "short_op": SHORT_OP,
        "short_length_cap": args.short_length_cap,
        "iou_dedup": args.iou_dedup,
        "genomes": {},
    }
    for genome in genomes:
        primary = decode_csv(primary_files[genome], PRIMARY_OP, "primary") if genome in primary_files else []
        short_all = decode_csv(short_files[genome], SHORT_OP, "short_rescue") if genome in short_files else []
        short = [r for r in short_all if (r[2] - r[1]) < args.short_length_cap]
        regions = union_dedup(primary, short, args.iou_dedup)

        out_csv = args.out_dir / f"{genome}_regions.csv"
        df = pd.DataFrame(
            regions,
            columns=["contig", "start", "end", "max_score", "source_scale"],
        )
        df.insert(0, "genome", genome)
        df.to_csv(out_csv, index=False)
        all_rows.append(df)
        manifest["genomes"][genome] = {
            "n_primary_regions": len(primary),
            "n_short_regions_raw": len(short_all),
            "n_short_regions_kept": len(short),
            "n_regions": len(regions),
            "regions_csv": out_csv.name,
        }
        print(
            f"[{genome}] primary={len(primary)} short={len(short)}/{len(short_all)} "
            f"final={len(regions)}",
            flush=True,
        )

    if all_rows:
        pd.concat(all_rows, ignore_index=True).to_csv(args.out_dir / "all_regions.csv", index=False)
    else:
        pd.DataFrame(
            columns=["genome", "contig", "start", "end", "max_score", "source_scale"]
        ).to_csv(args.out_dir / "all_regions.csv", index=False)
    (args.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"[done] {args.out_dir}")


if __name__ == "__main__":
    main()
